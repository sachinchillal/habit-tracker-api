CREATE TABLE categories (
    id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500) NULL,
    parent_id CHAR(36) NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    parent_scope CHAR(36) AS (IFNULL(parent_id, '00000000-0000-0000-0000-000000000000')) STORED,
    name_key VARCHAR(100) AS (TRIM(name)) STORED,
    PRIMARY KEY (id),
    UNIQUE KEY uq_categories_user_id (user_id, id),
    UNIQUE KEY uq_categories_parent_name (user_id, parent_scope, name_key),
    KEY idx_categories_parent (parent_id),
    KEY idx_categories_status (status),
    KEY idx_categories_user_parent (user_id, parent_id),
    CONSTRAINT fk_categories_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_categories_parent FOREIGN KEY (user_id, parent_id) REFERENCES categories (user_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_categories_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'ARCHIVED', 'DELETED')),
    CONSTRAINT chk_categories_name CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 1 AND 100),
    CONSTRAINT chk_categories_not_self CHECK (parent_id IS NULL OR parent_id <> id),
    CONSTRAINT chk_categories_id CHECK (id <> '00000000-0000-0000-0000-000000000000')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
